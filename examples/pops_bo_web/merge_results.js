#!/usr/bin/env node
// Merge validate.js shards: node merge_results.js part1.json part2.json ...
// Writes results.json, results.js and results.md (shards are concatenated in argument order).
const fs = require('fs'), path = require('path');
const parts = process.argv.slice(2).map(f => JSON.parse(fs.readFileSync(f, 'utf8')));
const res = { meta: { ...parts[0].res.meta }, runs: {}, complexity: {}, spacing: {} };
const md = [];
for (const { res: r, md: m } of parts) {
  Object.assign(res.runs, r.runs); Object.assign(res.complexity, r.complexity || {}); Object.assign(res.spacing, r.spacing || {});
  if (r.variantCheck && !res.variantCheck) res.variantCheck = r.variantCheck;
  md.push(...m);
}
const m = res.meta;
fs.writeFileSync(path.join(__dirname, 'results.json'), JSON.stringify(res));
fs.writeFileSync(path.join(__dirname, 'results.js'), '// generated by validate.js — do not edit\nwindow.POPS_RESULTS = ' + JSON.stringify(res) + ';\n');
fs.writeFileSync(path.join(__dirname, 'results.md'),
  `# Seeded validation (ρ = ${m.rho}, POPS/greedy K = ${m.K}, outcomes conditioned on data = ${m.discrepancy}, minimum spacing r = ${m.minSpacing}, ${m.nSeeds} seeds, ${m.iters} iterations, noise σ = ${m.noise}, initial region [${m.region}], ${m.gridN}-point grid)\n\n` +
  'Generated by `validate.js` (sharded) + `merge_results.js`. Regret = f(x_opt) − max f_true over measured x (noise-free). Recommendation regret = regret of the strategy\'s predicted optimum after the final measurement.\n' + md.join('\n') + '\n');
console.log('merged', parts.length, 'parts -> results.json, results.js, results.md');
